"""Exercise the header checker as a CLI in isolated Git repositories."""

from pathlib import Path
import subprocess
import sys

import pytest

CHECKER = Path(__file__).resolve().parents[1] / "tools" / "check_headers.py"
EAGLE = "# Copyright 2026 Eagle AI Corp.\n# SPDX-License-Identifier: LicenseRef-Eagle-4-Source-Available\n"


@pytest.fixture
def repo(tmp_path):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    return tmp_path


def run_checker(repo, *args):
    return subprocess.run([sys.executable, str(CHECKER), *args], cwd=repo, capture_output=True, text=True)


def test_check_fix_and_idempotence(repo):
    source = repo / "example.py"
    original = b'#!/usr/bin/env python3\n# coding: utf-8\n"""Module docstring."""\nfrom __future__ import annotations\n'
    source.write_bytes(original)
    source.chmod(0o755)
    result = run_checker(repo)
    assert result.returncode == 1
    assert "example.py" in result.stdout
    assert source.read_bytes() == original
    result = run_checker(repo, "--fix")
    assert result.returncode == 0, result.stderr + result.stdout
    expected = original.replace(b"# coding: utf-8\n", b"# coding: utf-8\n" + EAGLE.encode() + b"\n")
    assert source.read_bytes() == expected
    assert source.stat().st_mode & 0o777 == 0o755
    assert run_checker(repo).returncode == 0
    assert run_checker(repo, "--fix").returncode == 0
    assert source.read_bytes() == expected


