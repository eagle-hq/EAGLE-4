@pytest.mark.parametrize(
    "name,preamble,body",
    [
        ("kernel.cu", b"", b"int x;\n"),
        ("kernel.hpp", b"", b"#pragma once\n"),
        ("run.sh", b"#!/bin/sh\n", b"exit 0\n"),
        ("plan.env", b"", b"export OMP_NUM_THREADS=4\n"),
        ("run", b"#!/usr/bin/env python3\n", b"pass\n"),
        ("rules.sky", b"", b"x = 1\n"),
        ("docker/test.Dockerfile", b"", b"FROM scratch\n"),
        ("Dockerfile", b"# syntax=docker/dockerfile:1\n", b"FROM scratch\n"),
        (
            "docker/directives.Dockerfile",
            b"# syntax=docker/dockerfile:1\n# escape=`\n# check=error=true\n",
            b"FROM scratch\n",
        ),
        ("Dockerfile", b"# SyNtAx = docker/dockerfile:1\n", b"FROM scratch\n"),
        ("scripts/helper.py", b"", b"pass\n"),
        ("latin.py", b"# coding: latin-1\n", b"# caf\xe9\npass\n"),
        ("bom.py", b"\xef\xbb\xbf", b"pass\n"),
        ("crlf.py", b"#!/usr/bin/env python3\r\n", b"pass\r\n"),
        ("comment.py", b"", b"# default width: derived from the cost table\npass\n"),
        ("empty.py", b"", b""),
    ],
)
def test_source_forms_preserve_bytes(repo, name, preamble, body):
    path = repo / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(preamble + body)
    result = run_checker(repo, "--fix")
    assert result.returncode == 0, result.stdout + result.stderr
    header = EAGLE.replace("#", "//") if path.suffix in (".cu", ".hpp") else EAGLE
    newline = b"\r\n" if b"\r\n" in preamble else b"\n"
    separator = newline if body else b""
    assert path.read_bytes() == preamble + header.encode().replace(b"\n", newline) + separator + body
    assert run_checker(repo).returncode == 0


@pytest.mark.parametrize("newline", [b"\n", b"\r\n", b"\r"])
def test_preserves_newlines_and_unterminated_source(repo, newline):
    path = repo / "unterminated.py"
    preamble = b"#!/usr/bin/env python3" + newline + b"# coding: utf-8" + newline
    body = b'"""Module docstring."""' + newline + b"pass"
    path.write_bytes(preamble + body)
    result = run_checker(repo, "--fix")
    assert result.returncode == 0, result.stdout + result.stderr
    assert path.read_bytes() == preamble + EAGLE.encode().replace(b"\n", newline) + newline + body
    assert run_checker(repo).returncode == 0


@pytest.mark.parametrize("tracked", [False, True])
@pytest.mark.parametrize(
    "header",
    [
        "",
        "# Copyright 2026 Eagle AI Corp.\n# SPDX-License-Identifier: MIT\n",
        "# Copyright 2025 Eagle AI Corp.\n# SPDX-License-Identifier: LicenseRef-Eagle-4-Source-Available\n",
        "# Copyright 2026 Not Eagle Corp.\n# SPDX-License-Identifier: LicenseRef-Eagle-4-Source-Available\n",
    ],
)
def test_rejects_missing_or_incorrect_new_headers(repo, tracked, header):
    path = repo / "new.py"
    path.write_text(header + "pass\n")
    if tracked:
        subprocess.run(["git", "add", "new.py"], cwd=repo, check=True)
    original = path.read_bytes()
    result = run_checker(repo)
    assert result.returncode == 1
    assert "new.py" in result.stdout
    assert path.read_bytes() == original
    if header:
        assert run_checker(repo, "--fix").returncode == 1
        assert path.read_bytes() == original


def test_skips_ignored_files_and_symlinks_but_checks_tracked(repo):
    (repo / ".gitignore").write_text("ignored.py\ntracked.py\n")
    ignored = repo / "ignored.py"
    ignored.write_text("pass\n")
    (repo / "link.py").symlink_to(ignored)
    assert run_checker(repo, "--fix").returncode == 0
    assert ignored.read_text() == "pass\n"
    assert (repo / "link.py").is_symlink()
    (repo / "tracked.py").write_text("pass\n")
    subprocess.run(["git", "add", "-f", "tracked.py"], cwd=repo, check=True)
    result = run_checker(repo)
    assert result.returncode == 1
    assert "tracked.py" in result.stdout


@pytest.mark.parametrize("partial", EAGLE.splitlines(keepends=True))
def test_repairs_partial_eagle_header_without_duplicate(repo, partial):
    path = repo / "partial.py"
    path.write_text(partial + "pass\n")
    result = run_checker(repo)
    assert result.returncode == 1
    assert path.read_text() == partial + "pass\n"
    result = run_checker(repo, "--fix")
    assert result.returncode == 0, result.stdout + result.stderr
    assert path.read_text() == EAGLE + "\npass\n"
    assert run_checker(repo).returncode == 0
