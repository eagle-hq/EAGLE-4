"""Check source headers, or add missing lines with ``--fix``.

Run from a Git checkout. Include tracked and non-ignored untracked source files.
Legal files, documentation, data and generated files are outside this check.
Preserve recognized upstream notices. Refuse conflicting or unknown provenance
without rewriting it; a maintainer must review it against THIRD_PARTY_NOTICES.md.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

COPYRIGHT = "Copyright 2026 Eagle AI Corp."
LICENSE = "SPDX-License-Identifier: LicenseRef-Eagle-4-Source-Available"
SOURCE_SUFFIXES = {
    ".py",
    ".pyi",
    ".sh",
    ".bash",
    ".env",
    ".c",
    ".cc",
    ".cpp",
    ".cxx",
    ".h",
    ".hpp",
    ".cu",
    ".cuh",
    ".sky",
}
C_SUFFIXES = {".c", ".cc", ".cpp", ".cxx", ".h", ".hpp", ".cu", ".cuh"}
ENCODING = re.compile(rb"^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+")


def add_header(path: Path, data: bytes) -> bytes:
    if data.startswith(b"\xef\xbb\xbf"):
        return b"\xef\xbb\xbf" + add_header(path, data[3:])
    lines = data.splitlines(keepends=True)
    position = int(bool(lines and lines[0].startswith(b"#!")))
    for index, line in enumerate(lines[:2]):
        if ENCODING.match(line):
            position = index + 1
    if path.name == "Dockerfile" or path.suffix == ".Dockerfile":
        # Docker stops reading parser directives at the first ordinary comment.
        for index, line in enumerate(lines):
            if not re.match(rb"(?i)^\s*#\s*(syntax|escape|check)\s*=", line):
                break
            position = index + 1
    prefix = "//" if path.suffix in C_SUFFIXES else "#"
    first_newline = re.search(rb"\r\n|\n|\r", data)
    newline = first_newline.group() if first_newline else b"\n"
    comments = []
    for line in lines[position:]:
        if line.strip() and not line.lstrip().startswith((b"#", b"//", b"/*", b"*")):
            break
        comments.append(line)
    notice = b"".join(comments)
    if re.search(rb"(?i)lightseek|(?:copyright|derived from)[^\n]*tokenspeed", notice):
        raise ValueError("TokenSpeed/LightSeek provenance is not allowed here; left untouched")
    if re.search(rb"(?im)^\s*(?:#|//|/\*|\*)\s*(?:code generated|generated by|@generated|auto-generated)\b", notice):
        return data
    if b"Advanced Micro Devices" in notice:
        amd_header = {
            f"{prefix} Copyright (c) 2026 Advanced Micro Devices, Inc.".encode(),
            f"{prefix} SPDX-License-Identifier: Apache-2.0".encode(),
        }
        legal_lines = {line for line in notice.splitlines() if re.search(rb"(?i)copyright|SPDX-License", line)}
        if legal_lines != amd_header:
            raise ValueError("incorrect AMD copyright/license; review manually, left untouched")
        return data
    upstream = (b"SGLang Team", b"vLLM project", b"vLLM contributors", b"Tri Dao", b"FlashInfer", b"SafeAI Lab")
    if b"SPDX-FileCopyrightText:" in notice and any(holder in notice for holder in upstream):
        if re.search(rb"(?i)copyright[^\n]*Eagle AI Corp|LicenseRef-Eagle-", notice):
            raise ValueError("conflicting Eagle header on derived source; review manually, left untouched")
        return data
    expected = [f"{prefix} {line}".encode() for line in (COPYRIGHT, LICENSE)]
    for line in notice.splitlines():
        if (
            re.search(
                rb"(?i)copyright|SPDX-License-Identifier|^\s*(?:#|//|/\*|\*)\s*(?:derived from|licensed under)", line
            )
            and line not in expected
        ):
            raise ValueError("unrecognized copyright/license/provenance; review manually, left untouched")
    header = newline.join(expected) + newline
    if b"".join(lines[position:]).startswith(header):
        return data
    remaining_comments = [line for line in comments if line.rstrip(b"\r\n") not in expected]
    body = b"".join(remaining_comments + lines[position + len(comments) :])
    preamble = b"".join(lines[:position])
    if preamble and not preamble.endswith((b"\n", b"\r")):
        preamble += newline
    return preamble + header + (newline + body if body else b"")


def check_third_party(root: Path, manifest: Path) -> tuple[set[str], int]:
    """Validate known provenance before the generic Eagle-header fixer runs."""
    records = json.loads(manifest.read_text())["files"]
    names: set[str] = set()
    seen: set[str] = set()
    errors = 0
    for record in records:
        name = record["path"]
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts or name in seen:
            raise ValueError(f"invalid or duplicate manifest path: {name}")
        seen.add(name)
        names.add(name)
        path = root / relative
        if not path.exists() and record.get("absent_in_baseline", False):
            continue
        if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(root.resolve()):
            print(f"{name}: missing source or unsafe symlink")
            errors += 1
            continue
        data = path.read_bytes()
        eagle_header = f"# {COPYRIGHT}\n# {LICENSE}\n".encode()
        first_party_body = data.removeprefix(eagle_header).lstrip(b"\r\n")
        if hashlib.sha256(first_party_body).hexdigest() in record.get("first_party_sha256", []):
            names.remove(name)
            continue
        lines = data.decode("utf-8-sig").splitlines()
        comments = []
        prefixes = ("//", "/*", "*") if path.suffix in C_SUFFIXES else ("#",)
        for line in lines:
            if line.strip() and not line.lstrip().startswith(prefixes):
                break
            comments.append(line)
        header = "\n".join(comments) + "\n"
        notice = record["notice"]
        if not notice or notice not in header:
            print(f"{name}: missing original notice")
            errors += 1
        if record["modified"] and not re.search(r"(?m)^(?:#|//) Modified by Eagle AI Corp\.$", header):
            print(f"{name}: missing modification notice")
            errors += 1
        if re.search(r"(?i)copyright[^\n]*Eagle AI Corp|LicenseRef-Eagle-", header):
            print(f"{name}: conflicting Eagle ownership on derived source")
            errors += 1
        expected_spdx = re.findall(r"SPDX-License-Identifier:[^\n]*", notice)
        actual_spdx = re.findall(r"SPDX-License-Identifier:[^\n]*", header)
        if actual_spdx != expected_spdx:
            print(f"{name}: changed SPDX license")
            errors += 1
    return names, errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fix", action="store_true", help="add missing Eagle headers; never repair derived source")
    parser.add_argument("--manifest", type=Path, help="third-party provenance manifest")
    parser.add_argument("--root", type=Path, help="source root (also accepts an extracted engine tree)")
    parser.add_argument("--third-party-only", action="store_true", help="check only the manifest, not Eagle ownership")
    args = parser.parse_args()
    root = args.root or Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())
    manifest = args.manifest or root / "tools" / "third_party_headers.json"
    derived: set[str] = set()
    missing = 0
    try:
        if manifest.exists():
            derived, missing = check_third_party(root, manifest)
        elif args.manifest or args.third_party_only:
            raise ValueError(f"missing provenance manifest: {manifest}")
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"provenance manifest: {error}")
        return 1
    if args.third_party_only:
        return int(missing > 0)
    names = subprocess.check_output(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=root)
    for name in sorted(set(names.decode().split("\0")) - {""}):
        if name in derived:
            continue
        path = root / name
        if {"docs", "LICENSES", "legal", "data", "generated"}.intersection(Path(name).parts):
            continue
        if not path.is_file() or path.is_symlink():
            continue
        data = path.read_bytes()
        is_script = data.startswith(b"#!") and re.search(rb"(?:python[\d.]*|(?:ba|z|da|k)?sh)\b", data.splitlines()[0])
        if (
            path.suffix not in SOURCE_SUFFIXES
            and path.name != "Dockerfile"
            and path.suffix != ".Dockerfile"
            and not is_script
        ):
            continue
        try:
            updated = add_header(path, data)
        except ValueError as error:
            missing += 1
            print(f"{name}: {error}")
            continue
        if updated == data:
            continue
        if args.fix:
            path.write_bytes(updated)
            print(f"added: {name}")
        else:
            missing += 1
            print(f"missing header: {name} (run python tools/check_headers.py --fix)")
    return int(missing > 0)


if __name__ == "__main__":
    raise SystemExit(main())
